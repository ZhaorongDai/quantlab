"""Rebuild a CRSP daily store from the raw and reference tiers already on disk.

``CrspStoreRebuilder`` is the CRSP half of ``quantlab.base.rebuild``: it
names the sidecar files a CRSP store owns, says which converter writes the
store, and counts a handful of quality numbers once the store is written.
The order of operations (check inputs, back up, clear, convert, measure) and
every refusal live in ``BaseStoreRebuilder``.

A rebuild is offline. It reads the raw parquet tier and the reference tier
and writes the Zarr store; nothing here touches a vendor client, an endpoint
or a credential, so it needs no WRDS account and no network.
"""

from __future__ import annotations

from pathlib import Path

import xarray as xr

from quantlab.base.rebuild import BaseStoreRebuilder
from quantlab.dataset._support.cleaning import REQUIRED_COLUMNS

#: Every sidecar that belongs to a CRSP store, as a suffix on the store path:
#:
#: - ``.chunks.json``: the chunk ledger recording which windows were written,
#:   which the next append reconciles against.
#: - ``.crsp_adjustment.json``: no longer generated by the conversion. It is
#:   kept here so that a rebuild over a store written by an older version
#:   still clears it.
#: - ``.crsp_filter_report.json``: what the security filter dropped and what
#:   an explicit roster overrode.
#: - ``.crsp_symbology_report.json``: no longer generated; kept here for the
#:   same reason as the adjustment file.
#: - ``.crsp_tickers.json``: the PERMNO-to-ticker interval table a display
#:   layer reads to spell the integer axis.
#:
#: All five must be deleted before a rebuild, not only the store directory.
#: The conversion skips writing its reports when the store already exists
#: (so an append never overwrites a surviving store's audit trail), which
#: means a rebuild that removed only the ``.zarr`` directory would finish
#: with audit files describing the previous panel beside the new one. A
#: suffix dropped from this list would likewise leave a stale file beside a
#: store it never described.
CRSP_SIDECAR_SUFFIXES: tuple[str, ...] = (
    ".chunks.json",
    ".crsp_adjustment.json",
    ".crsp_filter_report.json",
    ".crsp_symbology_report.json",
    ".crsp_tickers.json",
)


class CrspStoreRebuilder(BaseStoreRebuilder):
    """Re-convert one CRSP store from the raw tier and measure the result.

    Examples
    --------
    >>> from quantlab.base.config import CrspDatasetConfig
    >>> from quantlab.dataset.crsp.rebuild import CrspStoreRebuilder
    >>> config = CrspDatasetConfig(
    ...     zarr_file_path="data/data/us_equity/1d/crsp.zarr",
    ...     raw_data_dir_path="data/downloads/us_equity/1d/wrds_crsp/wrds",
    ...     catalog_path="data/data/catalog",
    ...     reference_dir="data/downloads/us_equity/1d/wrds_crsp/_reference",
    ...     start_date="2024-01-01",
    ...     end_date="2024-12-31",
    ...     security_filter="equity_common",
    ...     roster_universe="crsp_sp500",
    ... )
    >>> rebuilder = CrspStoreRebuilder(config, data_root="/path/to/repo")
    >>> [p.name for p in rebuilder.sidecar_paths()][:2]
    ['crsp.zarr.chunks.json', 'crsp.zarr.crsp_adjustment.json']
    >>> measurement = rebuilder.rebuild(backup_dir=Path("/path/to/backup"))

    The last line needs a real raw and reference tier under ``data_root``;
    without them ``rebuild()`` refuses before deleting anything.
    """

    SIDECAR_SUFFIXES = CRSP_SIDECAR_SUFFIXES

    def _required_inputs(self) -> tuple[Path, ...]:
        """Return the raw vendor directory and the reference directory.

        Both are resolved against ``data_root``; an absolute config path is
        used as-is, so configs written with absolute and repository-relative
        paths land in the same place and neither falls through to the
        current working directory.

        Two path traps: ``raw_data_dir_path`` must end at the ``/wrds``
        vendor segment (the dataset refuses a root one level up), and
        ``reference_dir`` is a sibling of ``wrds_crsp`` named ``_reference``,
        not a child of ``wrds``.
        """
        return (
            self.data_root / str(self.config.raw_data_dir_path),
            self.data_root / str(self.config.reference_dir),
        )

    def _convert(self) -> object:
        """Re-run the offline conversion and return its ``ConversionResult``.

        The imports are function-local so that importing the rebuilder does
        not load ``quantlab.acquisition``. ``on_new_listing="refuse"`` is
        deliberate: a rebuild is meant to reproduce a known panel, and a
        listing that appears out of nowhere means the raw tier is not the one
        the measurements were taken against.
        """
        from quantlab.registry import convert
        from quantlab.acquisition.wrds import WRDS_SOURCE

        return convert(
            WRDS_SOURCE,
            self.config,
            data_type="crsp_daily",
            granularity="year",
            on_new_listing="refuse",
        )

    def _measure(self) -> dict[str, int]:
        """Return seven quality counts read from the written store.

        ``structural_gaps`` uses the same definition of an empty cell as the
        cleaning step: a logical AND over ``isnull()`` of every column in
        ``REQUIRED_COLUMNS``, imported from there rather than re-listed.
        ``anomaly_flag_true`` is 0 on a panel with no ``anomaly_flag``
        variable, which is a measurement rather than an error.
        """
        panel = xr.open_zarr(self.store_path)
        try:
            structural_mask = None
            for column in REQUIRED_COLUMNS:
                is_null = panel[column].isnull()
                structural_mask = (
                    is_null
                    if structural_mask is None
                    else (structural_mask & is_null)
                )

            anomaly_flag_true = (
                int(panel["anomaly_flag"].sum())
                if "anomaly_flag" in panel.data_vars
                else 0
            )

            return {
                "anomaly_flag_true": anomaly_flag_true,
                "adj_close_le_zero": int((panel["adjClose"] <= 0).sum()),
                "close_eq_zero": int((panel["close"] == 0).sum()),
                "adj_close_nan": int(panel["adjClose"].isnull().sum()),
                "adj_volume_nan": int(panel["adjVolume"].isnull().sum()),
                "structural_gaps": (
                    0 if structural_mask is None else int(structural_mask.sum())
                ),
                "symbol_count": int(panel.sizes["symbol"]),
            }
        finally:
            panel.close()

    def _measure_dims(self) -> tuple[dict[str, int], int]:
        """Return ``(dict(panel.sizes), len(panel.data_vars))`` of the store."""
        panel = xr.open_zarr(self.store_path)
        try:
            return dict(panel.sizes), len(panel.data_vars)
        finally:
            panel.close()
